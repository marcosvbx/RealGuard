def current() -> str:
    value = os.getenv("REALGUARD_UI_LOCALE", "pt-BR")
    return value if value in SUPPORTED else "pt-BR"


def translate(text: str) -> str:
    catalog = {"en": _EN, "es": _ES}.get(current())
    if not catalog:
        return text
    # Maior expressão primeiro, para não traduzir partes antes da frase inteira.
    for source, target in sorted(catalog.items(), key=lambda item: -len(item[0])):
        text = text.replace(source, target)
    return text
